#!/usr/bin/env python3
"""
make_blueprints.py  --  create paper recipes ("blueprints") that respect your subject weightage.

GATE CSE paper = 65 questions / 100 marks:
    General Aptitude : 5 x 1-mark + 5 x 2-mark                       = 15 marks
    Core subjects    : 25 x 1-mark + 30 x 2-mark = 55 questions       = 85 marks
Each core subject gets a mark total inside its [min, max] range (the table you gave me); the 85 marks are split
at random, leaning toward High-priority subjects, and each subject's marks are then split into 1-mark / 2-mark
questions so the paper-wide totals come out exactly 25 and 30.

    python make_blueprints.py                 # 30 blueprints -> ../seed/002_blueprints.sql
    python make_blueprints.py --count 60 --seed 7
    python make_blueprints.py --check         # print one blueprint + self-test 5000 random ones

Run the generated SQL in Supabase after 001_subjects.sql. Safe to re-run (replaces blueprints named 'Standard-xx').
"""
import argparse, random
from pathlib import Path

# keep in sync with seed/001_subjects.sql  (code, min, max, priority-weight)
CORE = [("PDS", 10, 15, 3), ("MATH", 13, 15, 3), ("ALGO", 7, 12, 3), ("OS", 8, 12, 3), ("CN", 8, 12, 2),
        ("COA", 7, 10, 2), ("TOC", 7, 10, 2), ("DBMS", 6, 10, 2), ("CD", 4, 6, 1), ("DL", 4, 6, 1)]
CORE_MARKS, CORE_ONE, CORE_TWO = 85, 25, 30
GA = ("GA", 5, 5)                                   # (code, one-mark count, two-mark count)


def sample(rng):
    """-> {code: (n_one, n_two)} for the 10 core subjects, or raises if the ranges make it impossible."""
    assert sum(lo for _, lo, _, _ in CORE) <= CORE_MARKS <= sum(hi for _, _, hi, _ in CORE), "weightage ranges can't sum to 85"
    marks = {c: lo for c, lo, _, _ in CORE}
    rng_info = {c: (lo, hi, w) for c, lo, hi, w in CORE}
    left = CORE_MARKS - sum(marks.values())
    while left > 0:                                  # hand out the spare marks one by one
        open_ = [c for c in marks if marks[c] < rng_info[c][1]]
        c = rng.choices(open_, weights=[rng_info[x][2] for x in open_])[0]
        marks[c] += 1; left -= 1
    one = {c: m % 2 for c, m in marks.items()}       # parity forces at least m%2 one-mark questions
    need = CORE_ONE - sum(one.values())              # extra one-mark questions, added in pairs (2 one-marks = 1 two-mark)
    assert need >= 0 and need % 2 == 0
    while need > 0:
        open_ = [c for c in marks if one[c] + 2 <= marks[c]]
        c = rng.choice(open_); one[c] += 2; need -= 2
    return {c: (one[c], (marks[c] - one[c]) // 2) for c in marks}


def check(bp):
    n1 = sum(a for a, _ in bp.values()) + GA[1]; n2 = sum(b for _, b in bp.values()) + GA[2]
    assert (n1, n2) == (30, 35) and n1 + n2 == 65 and n1 + 2 * n2 == 100, (n1, n2)
    for c, lo, hi, _ in CORE:
        m = bp[c][0] + 2 * bp[c][1]
        assert lo <= m <= hi, (c, m)
    assert sum(a for a, _ in bp.values()) == CORE_ONE and sum(b for _, b in bp.values()) == CORE_TWO


def to_sql(blueprints):
    out = ["-- seed/002_blueprints.sql  (generated by tools/make_blueprints.py - do not edit by hand)",
           "delete from blueprints where name like 'Standard-%';"]
    for i, bp in enumerate(blueprints, 1):
        name = f"Standard-{i:02d}"
        out.append(f"with b as (insert into blueprints (name, duration_min, total_questions, total_marks) "
                   f"values ('{name}', 180, 65, 100) returning id)")
        rows = [(GA[0], 1, GA[1]), (GA[0], 2, GA[2])]
        for c, (a, b2) in bp.items():
            rows += [(c, 1, a), (c, 2, b2)]
        vals = ",\n  ".join(f"('{c}', {m}, {n})" for c, m, n in rows if n > 0)
        out.append("insert into blueprint_rules (blueprint_id, subject_id, marks, qcount)\n"
                   "select b.id, s.id, v.marks, v.n from b, (values\n  " + vals +
                   "\n) as v(code, marks, n) join subjects s on s.code = v.code;\n")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--count", type=int, default=30); ap.add_argument("--seed", type=int, default=2026)
    ap.add_argument("--out", default=str(Path(__file__).resolve().parents[1] / "supabase" / "seed" / "002_blueprints.sql"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    rng = random.Random(a.seed)
    if a.check:
        for _ in range(5000):
            check(sample(rng))
        bp = sample(rng)
        print("5000 random blueprints satisfy every rule (65 Q, 100 marks, 25x1 + 30x2 core, ranges respected). Example:")
        for c, lo, hi, _ in CORE:
            a1, a2 = bp[c]; print(f"  {c:5s} {a1}x1 + {a2}x2 = {a1 + 2 * a2:2d} marks   (allowed {lo}-{hi})")
        return
    bps = []
    seen = set()
    while len(bps) < a.count:
        bp = sample(rng); check(bp)
        key = tuple(sorted(bp.items()))
        if key not in seen:
            seen.add(key); bps.append(bp)
    Path(a.out).write_text(to_sql(bps), encoding="utf-8")
    print(f"wrote {len(bps)} blueprints -> {a.out}")


if __name__ == "__main__":
    main()
